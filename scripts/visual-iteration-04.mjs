import fs from "node:fs/promises";
import path from "node:path";
import { chromium } from "playwright-core";

const baseUrl = process.env.APP_URL ?? "http://127.0.0.1:3002";
const outputDir = path.resolve("screenshots", "iteration-04");
await fs.mkdir(outputDir, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH ?? "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, hasTouch: true });
const page = await context.newPage();
const errors = [];
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
page.on("pageerror", (error) => errors.push(error.message));
await page.goto(baseUrl, { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.locator(".day-cover.is-active").waitFor();
await page.screenshot({ path: path.join(outputDir, "01-traza-header-day-carousel.png") });

const carousel = page.locator(".day-carousel");
await carousel.focus();
await page.keyboard.press("Home");
for (let i = 0; i < 4; i += 1) await page.keyboard.press("ArrowRight");
await page.waitForTimeout(250);
await page.screenshot({ path: path.join(outputDir, "02-portadas-dias-06-10.png") });

await page.locator(".day-cover.is-active .open-day-handle").click();
await page.locator(".day-open-layer").waitFor();
await page.screenshot({ path: path.join(outputDir, "03-dia-normal.png") });
await page.getByRole("button", { name: "Organizar" }).click();
await page.getByRole("toolbar", { name: /Guardar cambios/ }).waitFor();
await page.screenshot({ path: path.join(outputDir, "04-organizar-normal.png") });
const lockedCount = await page.getByText(/Fijo · no se mueve/).count();
await page.getByRole("button", { name: "Mover abajo" }).first().click().catch(() => undefined);
await page.getByRole("button", { name: "Guardar cambios" }).click();
await page.getByRole("status").filter({ hasText: /Cambios de organización/ }).waitFor();
await page.screenshot({ path: path.join(outputDir, "05-organizar-guardado.png") });

await page.getByRole("button", { name: /Cerrar el itinerario/ }).click();
await page.getByRole("button", { name: /Guardados/ }).click();
await page.locator(".saved-editorial-list").waitFor();
const mapHref = await page.locator(".saved-maps-link").first().getAttribute("href");
await page.screenshot({ path: path.join(outputDir, "06-guardados-maps.png") });
const mms = page.locator(".saved-card").filter({ hasText: "M&M's London" }).first();
await mms.getByRole("button").first().click();
await page.getByRole("dialog").waitFor();
await page.getByText(/¿En qué día encaja|¿Dónde quieres colocarlo?/).first().waitFor().catch(() => undefined);
await page.locator(".assignment-days button").first().click();
await page.getByText("¿Dónde quieres colocarlo?").waitFor();
await page.getByText("¿Dónde quieres colocarlo?").scrollIntoViewIfNeeded();
await page.screenshot({ path: path.join(outputDir, "07-colocacion-guardados.png") });
const placementStep = await page.getByText("¿Dónde quieres colocarlo?").count();
await page.getByRole("button", { name: "Cerrar" }).last().click().catch(() => undefined);
await page.getByRole("button", { name: /Viaje/ }).click();
await page.locator(".trip-view").waitFor();
await page.screenshot({ path: path.join(outputDir, "08-viaje.png") });
const mapsCount = await page.locator('a[href*="google.com/maps/search"]').count();
const report = { viewport: "390x844", lockedCount, placementStep: placementStep > 0, mapsHref: mapHref, mapsCount, consoleErrors: errors };
await fs.writeFile(path.join(outputDir, "validation.json"), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
await browser.close();
